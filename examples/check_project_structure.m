%CHECK_PROJECT_STRUCTURE Verify the MATLAB project structure and public APIs.
%   Run this script from any working directory. It checks directories,
%   required files, package resolution, the engine and reserved capability API.
%   The original MATLAB path is restored on completion or failure.

checkProjectStructure(fileparts(fileparts(mfilename('fullpath'))));

function checkProjectStructure(projectRoot)
requiredDirectories = { ...
    'src', ...
    'src/+avlc', ...
    'src/+avlc/+core', ...
    'src/+avlc/+model', ...
    'src/+avlc/+dynamics', ...
    'src/+avlc/+scenario', ...
    'src/+avlc/+scenario/presets', ...
    'src/+avlc/+analysis', ...
    'src/+avlc/+result', ...
    'src/+avlc/+visualization', ...
    'src/+avlc/+io', ...
    'app', 'scenarios', 'tests', 'examples', 'data', ...
    'docs', 'docs/requirements', 'docs/architecture'};

for index = 1:numel(requiredDirectories)
    directory = fullfile(projectRoot, requiredDirectories{index});
    assert(isfolder(directory), 'AVLC:MissingDirectory', ...
        'Required directory is missing: %s', directory);
end

requiredFiles = { ...
    'README.md', ...
    'src/+avlc/+core/runSimulation.m', ...
    'src/+avlc/+analysis/evaluateCapability.m', ...
    'examples/check_project_structure.m'};

for index = 1:numel(requiredFiles)
    file = fullfile(projectRoot, requiredFiles{index});
    assert(isfile(file), 'AVLC:MissingFile', ...
        'Required file is missing: %s', file);
end

originalPath = path;
restorePath = onCleanup(@() path(originalPath)); %#ok<NASGU>
addpath(fullfile(projectRoot, 'src'));

functionNames = { ...
    'avlc.core.runSimulation', ...
    'avlc.analysis.evaluateCapability'};
expectedPaths = { ...
    fullfile(projectRoot, 'src', '+avlc', '+core', 'runSimulation.m'), ...
    fullfile(projectRoot, 'src', '+avlc', '+analysis', 'evaluateCapability.m')};

for index = 1:numel(functionNames)
    resolvedPath = which(functionNames{index});
    if ispc
        matches = strcmpi(resolvedPath, expectedPaths{index});
    else
        matches = strcmp(resolvedPath, expectedPaths{index});
    end
    assert(matches, 'AVLC:PackageResolutionFailed', ...
        'Expected %s to resolve to %s; resolved to: %s', ...
        functionNames{index}, expectedPaths{index}, resolvedPath);
end

assertExpectedError(@() avlc.core.runSimulation(struct(), struct(), struct()), ...
    'AVLC:InvalidScenario');
road = avlc.model.createRoad(3.6, [-50, 50]);
params = avlc.model.createTheoryModelParameters(2, 4, 3, 0, 0, 0, 0);
roles = {'EGO', 'FO', 'RO', 'RT'};
vehicles = cell(1, 4);
for index = 1:4
    state = avlc.model.createVehicleState(0, 0, 1, 0, 0, 0);
    vehicles{index} = avlc.model.createVehicle(string(index), roles{index}, 4, 2, state);
end
scenario = avlc.scenario.createScenario("structure check", "", road, params, vehicles{:});
result = avlc.core.runSimulation(scenario, ...
    avlc.model.createSimulationConfig(0.1, 0.1), avlc.model.createControl(0, 0));
assert(isequal(fieldnames(result), {'time'; 'states'; 'controls'; 'metadata'}) && ...
    numel(result.states.EGO) == 2 && numel(result.controls.EGO) == 1, ...
    'AVLC:EngineStructureFailed', 'The engine must return N+1 states and N controls.');
assertExpectedError(@() avlc.analysis.evaluateCapability( ...
    struct(), struct(), struct()), 'AVLC:CapabilityNotImplemented');

fprintf('Project structure verification passed (P0.2.5 engine).\n');
end

function assertExpectedError(callback, expectedIdentifier)
try
    callback();
catch exception
    assert(strcmp(exception.identifier, expectedIdentifier), ...
        'AVLC:UnexpectedError', 'Expected %s; received %s: %s', ...
        expectedIdentifier, exception.identifier, exception.message);
    return;
end
error('AVLC:MissingExpectedError', ...
    'Call returned without raising %s.', expectedIdentifier);
end
